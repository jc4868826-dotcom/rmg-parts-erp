async function seed() {
  console.log('🌱 Iniciando seed de productos RMG...');
  console.log(`   Total productos a insertar: ${PRODUCTOS.length}`);

  const { data, error } = await supabase
    .from('productos')
    .upsert(PRODUCTOS, { onConflict: 'codigo' })
    .select();

  if (error) {
    console.error('❌ Error en seed:', error.message);
    process.exit(1);
  }

  console.log(`✅ ${data.length} productos insertados/actualizados correctamente`);

  // Resumen por categoría
  const porCategoria = PRODUCTOS.reduce((acc, p) => {
    acc[p.categoria] = (acc[p.categoria] || 0) + 1;
    return acc;
  }, {});

  console.log('\n📊 Resumen por categoría:');
  Object.entries(porCategoria).forEach(([cat, n]) => {
    console.log(`   ${cat}: ${n} productos`);
  });
}

seed().catch(console.error);
